// export.js — download the analysis result as Markdown / JSON.
// Browser-only (Blob + anchor download). Pure formatting, no network.

export function toMarkdown(result, buriedIds, revivalKit) {
  const buried = result.items.filter((i) => buriedIds.has(i.id));
  const open = result.items.filter((i) => i.state === 'open');
  const lines = [];
  lines.push('# Séance — Dead-code report');
  lines.push('');
  lines.push(`Scanned at ${result.scannedAt}. Files scanned: ${result.filesScanned}. Files skipped: ${result.filesSkipped.length}. Dead items: ${result.items.length}. Lines of dead code: ${result.deadLines}.`);
  lines.push('');
  if (buried.length) {
    lines.push('## Burial list (candidates for deletion)');
    lines.push('');
    for (const i of buried) {
      lines.push(`- \`${i.name}\` — ${i.file}:${i.line} (${i.kind}). ${i.cause}. Safety: ${i.explanation.safety}.`);
    }
    lines.push('');
  }
  if (revivalKit.length) {
    lines.push('## Revival kit (resurrected snippets)');
    lines.push('');
    for (const i of revivalKit) {
      lines.push(`- \`${i.name}\` — ${i.file}:${i.line}`);
      lines.push('  ```');
      lines.push(i.snippet);
      lines.push('  ```');
    }
    lines.push('');
  }
  lines.push('## All dead items');
  lines.push('');
  for (const i of open) {
    lines.push(`- \`${i.name}\` — ${i.file}:${i.line} (${i.kind}). ${i.cause}. Safety: ${i.explanation.safety}.`);
  }
  lines.push('');
  lines.push('_Generated by Séance (Kiroween 2026). Review every burial in a pull request before deleting._');
  return lines.join('\n');
}

export function download(filename, text, mime = 'text/plain') {
  const blob = new Blob([text], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
